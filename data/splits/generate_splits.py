"""
Generate train / validation / test split indices for the public datasets.

Note:
- ChestX-ray14: the paper (Section 4.3) uses 10,000 frontal images,
  7,000 train / 1,500 validation / 1,500 test.
  The paper specifies 10,000 images -> 7,000 / 1,500 / 1,500.
  contradicts Section 4.3. The .npy files in this package are now
  the 10,000-image splits, generated by this script with seed 42.
- DUD-E: the paper does not state split sizes. The DUD-E splits
  shipped here (17,000 train / 3,000 test from 20,000 molecules)
  are SUPPLEMENTARY and are labelled as such in the README.
  They are not claimed to be a paper-specified split.
"""
import numpy as np
from pathlib import Path

np.random.seed(42)
out = Path(__file__).parent

# NIH ChestX-ray14 — paper Section 4.3: 10,000 images
n_images = 10000
indices = np.arange(n_images)
np.random.shuffle(indices)
train_idx, val_idx, test_idx = indices[:7000], indices[7000:8500], indices[8500:10000]
np.save(out / "chestxray14_train_indices.npy", train_idx)
np.save(out / "chestxray14_val_indices.npy", val_idx)
np.save(out / "chestxray14_test_indices.npy", test_idx)

# DUD-E — supplementary, 20,000 molecules
n_mols = 20000
test_idx = np.random.choice(n_mols, size=3000, replace=False)
train_idx = np.setdiff1d(np.arange(n_mols), test_idx)
np.save(out / "dude_train_indices.npy", train_idx)
np.save(out / "dude_test_indices.npy", test_idx)

print("ChestX-ray14: train 7000 / val 1500 / test 1500 (seed 42)")
print("DUD-E (supplementary): train 17000 / test 3000 (seed 42)")
